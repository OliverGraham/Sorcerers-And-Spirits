package com.linklabs.sorcerersandspirits.data.authentication

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import com.linklabs.sorcerersandspirits.domain.authentication.SignInMethod
import com.linklabs.sorcerersandspirits.domain.authentication.SocialSignInProvider
import com.linklabs.sorcerersandspirits.domain.authentication.SocialTokenResult
import com.linklabs.sorcerersandspirits.platform.CurrentActivityHolder

// Generated by the google-services plugin into a string resource once an OAuth web client exists in
// google-services.json. It is read reflectively so this compiles before that client is configured
// (SS-088): until then the lookup misses and Google sign-in reports NotAvailable.
private const val WEB_CLIENT_ID_RESOURCE = "default_web_client_id"

class AndroidSocialSignInProvider(
    private val context: Context,
    private val currentActivityHolder: CurrentActivityHolder,
) : SocialSignInProvider {

    override suspend fun requestToken(method: SignInMethod): SocialTokenResult =
        when (method) {
            SignInMethod.GOOGLE -> requestGoogleToken()

            // Apple on Android needs a web OAuth flow (gitlive OAuthProvider), not Credential
            // Manager — out of scope for SS-086. Email never routes through this provider.
            SignInMethod.APPLE,
            SignInMethod.EMAIL -> SocialTokenResult.NotAvailable
        }

    private suspend fun requestGoogleToken(): SocialTokenResult {
        // The account-picker UI must be hosted by an Activity, not the application context.
        val activity = currentActivityHolder.activity ?: return SocialTokenResult.Error
        val webClientId = webClientId() ?: return SocialTokenResult.NotAvailable

        val googleOption = GetSignInWithGoogleOption.Builder(serverClientId = webClientId).build()
        val request =
            GetCredentialRequest.Builder()
                .addCredentialOption(credentialOption = googleOption)
                .build()

        return try {
            val response =
                CredentialManager.create(context = context)
                    .getCredential(context = activity, request = request)
            val credential = response.credential

            val isGoogleIdToken =
                credential is CustomCredential &&
                    credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL

            if (isGoogleIdToken) {
                val googleIdToken = GoogleIdTokenCredential.createFrom(data = credential.data)
                // Credential Manager's ID-token flow doesn't surface an OAuth access token; the
                // Android Firebase Google credential doesn't need one.
                SocialTokenResult.Google(idToken = googleIdToken.idToken, accessToken = null)
            } else {
                SocialTokenResult.Error
            }
        } catch (cancellation: GetCredentialCancellationException) {
            SocialTokenResult.Cancelled
        } catch (noCredential: NoCredentialException) {
            // No Google account available / dismissed before choosing one — treat as a cancel.
            SocialTokenResult.Cancelled
        } catch (parsing: GoogleIdTokenParsingException) {
            SocialTokenResult.Error
        } catch (error: GetCredentialException) {
            SocialTokenResult.Error
        }
    }

    private fun webClientId(): String? {
        val resourceId =
            context.resources.getIdentifier(WEB_CLIENT_ID_RESOURCE, "string", context.packageName)
        if (resourceId == 0) return null
        return context.getString(resourceId).takeIf { it.isNotBlank() }
    }
}
